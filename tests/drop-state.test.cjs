const assert=require('node:assert/strict');
global.window={};require('../drop-state.js');
const R=window.DFCHDropState, data=require('../data/stage-1.json');
const sample=id=>data.dropSamples.find(r=>r.dropItemSampleId===id);
const ordinary=sample(503),god=sample(505);
const start=R.begin(data,{daily:499});
const crossed=R.register(start,ordinary,10,data);
assert.equal(crossed.daily,509);assert.equal(crossed.limitReached,false);
assert.equal(start.daily,499);
const next=R.begin(data,R.commit(crossed));assert.equal(next.limitReached,true);
assert.equal(R.register(next,god,5000,data).daily,509);
assert.equal(R.pool([ordinary,god],next,data)[0].effectiveWeight,0);
assert.ok(R.pool([ordinary,god],next,data)[1].effectiveWeight>0);
assert.deepEqual(R.fallbackGroups(data).map(g=>g.id),[51,100150,100170]);
assert.equal(R.fallbackGroups(data,1.5).at(-1).weight,Math.fround(Math.fround(data.master.basicItemDropWeights[3])*Math.fround(1.5)));
const basic=R.distribution([50],next,data);
assert.equal(basic.basic,true);
assert.ok(!basic.rows.some(R.ordinaryDiamond));
assert.ok(basic.rows.some(r=>r.rewardId===305001000));
assert.ok(Math.abs(basic.rows.find(r=>r.dropItemSampleId===505).probability-god.weight/data.dropSamples.filter(r=>r.dropItemSampleGroupId===50).reduce((s,r)=>s+Math.fround(r.weight),0))<1e-12);
assert.ok(Math.abs(basic.rows.reduce((s,r)=>s+r.probability,0)+basic.noDropProbability-1)<1e-12);
const boss=R.distribution(data.master.bossDropSampleGroupIds,next,data);
assert.equal(boss.basic,false);assert.ok(!boss.rows.some(R.ordinaryDiamond));
assert.ok(Math.abs(boss.rows.reduce((s,r)=>s+r.probability,0)-1)<1e-12);
const artifact=data.dropSamples.find(r=>r.rewardId===301005002);
let state=R.begin(data,{owned:{301005002:3}});
assert.equal(R.artifactFull(artifact,state,data),false);
state=R.register(state,artifact,1,data);
assert.equal(R.artifactFull(artifact,state,data),true);
assert.equal(R.pool([artifact],state,data)[0].effectiveWeight,0);
assert.equal(R.begin(data,R.commit(state)).owned[301005002],4);
const unlocked=R.unlock(state,6602);
assert.equal(R.flagPool(data.flagUnlockSamples,unlocked).length,1);
assert.equal(R.flagPool(data.flagUnlockSamples,R.begin(data,R.commit(unlocked))).length,1);
assert.equal(R.flagPool(data.flagUnlockSamples,R.begin(data)).length,2);
assert.throws(()=>R.begin(data,{daily:-1}));assert.throws(()=>R.begin(data,{owned:{1:0.5}}));
assert.throws(()=>R.register(state,artifact,NaN,data));
const empty={...data,dropSamples:[],master:{...data.master,basicItemDropSampleGroupIds:[],basicItemDropWeights:[]}};
assert.equal(R.distribution([50],state,empty).noDropProbability,1);
console.log('drop-state: daily snapshot, God, fallback weights, ownership, flags and cross-run cases passed');
