const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/stage-1.json'), 'utf8'));
global.window = {};
require('../map-data.js');
assert.deepEqual(window.DFCHMapData, data);
assert.equal(data.master.dungeonId, 1001);
assert.equal(data.master.duration, 600);
assert.equal(data.master.depth, 60);
const rewards = new Set(data.rewardMasters.map(r => r.rewardId));
for (const row of data.dropSamples) assert.ok(row.rewardId === -1 || rewards.has(row.rewardId), `Unresolved reward ${row.rewardId}`);
const monsters = new Set(data.monsterNames.map(r => r.index));
for (const row of data.monsterSamples) assert.ok(monsters.has(row.monsterId));
for (const row of data.eventSamples.concat(data.conditionalTemplates)) assert.ok(data.eventSequences.some(s => s.logEventId === row.logEventId));
assert.ok(data.monsterSamples.some(r => r.isForceAppear && r.weight === 0));
assert.ok(data.dropSamples.some(r => r.rewardId === -1));
assert.equal(data.simulationPolicy.combat, 'instant-victory');
assert.equal(data.simulationPolicy.combatDurationSeconds, 0);
assert.equal(data.simulationPolicy.eventReplayImplemented, false);
assert.deepEqual(data.eventSequences.filter(s => s.logEventId === 1).map(s => s.functionType), [101,100,2]);
console.log('Map reference and offline data checks passed');
